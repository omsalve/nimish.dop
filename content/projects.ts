export type Category = (typeof CATEGORIES)[number]['key'];

export type Project = {
  slug: string;
  /**
   * True for the sample entries the site ships with. A placeholder shows a
   * "Sample entry" mark wherever it appears. Remove the flag (or the entry)
   * once real content is in.
   */
  placeholder?: boolean;
  /** Position in the reel at the top of the home page (1–4). Leave out for the rest. */
  reel?: number;
  title: string;
  category: Category;
  format: string;
  year: number;
  /** As printed, e.g. "14 min" or "60 s". */
  runtime: string;
  runtimeSeconds: number;
  /** As printed, e.g. "2.39:1". */
  aspect: string;
  /** Width ÷ height of the still, so the frame is never cropped where it is shown whole. */
  ratio: number;
  /** Nimish's roles on this film. */
  roles: string[];
  /** Who it was made for, when it is a commission. */
  client?: string;
  logline: string;
  still: Frame;
  /** Three to five frames from the film, in story order. */
  shots: KeyShot[];
  bts: BtsFrame[];
  concept: string[];
  role: string[];
  kit?: { camera?: string; lenses?: string; location?: string };
  credits: Credit[];
  /** The full film. When absent the page offers a screener on request instead. */
  film?: { url: string; label?: string };
  /**
   * A short silent loop (6–10 s, H.264 MP4, optional WebM) in /public, played
   * in the reel, on hover in the program and behind the title on the film's
   * page. Without one, the preview cuts between the still and the key shots.
   */
  preview?: { mp4: string; webm?: string };
};

